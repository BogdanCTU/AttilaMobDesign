// ============================================================
// Image optimisation – Mob Atidol
//
// Reads the original photos from  public/images/**  (never modified)
// and writes resized, compressed WebP variants to
// public/images-optimized/**  plus a manifest consumed by the app
// (src/config/imageManifest.ts) with intrinsic sizes & variant widths.
//
// Usage:  npm run optimize:images        (incremental)
//         npm run optimize:images -- --force
// ============================================================
import { readdir, mkdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC_DIR = path.join(ROOT, 'public', 'images')
const OUT_DIR = path.join(ROOT, 'public', 'images-optimized')
const MANIFEST = path.join(ROOT, 'src', 'config', 'imageManifest.ts')
const FORCE = process.argv.includes('--force')

// Responsive widths. Variants are never upscaled beyond the original.
const PROFILES = {
  // Full-bleed blurred section backgrounds: detail-free, so lower quality is invisible.
  background: { widths: [960, 1600], quality: 70 },
  // Project photos: grid thumbnails, carousel / cards, lightbox.
  default: { widths: [480, 960, 1600], quality: 80 },
}

const INPUT_EXT = new Set(['.jpg', '.jpeg', '.png'])

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = await Promise.all(entries.map((e) => {
    const full = path.join(dir, e.name)
    return e.isDirectory() ? walk(full) : INPUT_EXT.has(path.extname(e.name).toLowerCase()) ? [full] : []
  }))
  return files.flat()
}

async function isFresh(input, output) {
  try {
    const [i, o] = await Promise.all([stat(input), stat(output)])
    return o.mtimeMs >= i.mtimeMs
  } catch {
    return false
  }
}

const kb = (b) => `${(b / 1024).toFixed(0)} KB`
const mb = (b) => `${(b / 1024 / 1024).toFixed(2)} MB`

async function processFile(file) {
  const rel = path.relative(SRC_DIR, file)
  const relPosix = rel.split(path.sep).join('/')
  const category = relPosix.split('/')[0]
  const profile = PROFILES[category] ?? PROFILES.default

  // Honour EXIF orientation so portrait phone photos are not sideways.
  const meta = await sharp(file).metadata()
  const swap = (meta.orientation ?? 1) >= 5
  const width = swap ? meta.height : meta.width
  const height = swap ? meta.width : meta.height

  const widths = [...new Set(profile.widths.map((w) => Math.min(w, width)))].sort((a, b) => a - b)
  const outBase = path.join(OUT_DIR, rel.replace(/\.[^.]+$/, ''))
  await mkdir(path.dirname(outBase), { recursive: true })

  let outBytes = 0
  for (const w of widths) {
    const out = `${outBase}-${w}.webp`
    if (FORCE || !(await isFresh(file, out))) {
      await sharp(file)
        .rotate()
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: profile.quality, effort: 6, smartSubsample: true })
        .toFile(out)
    }
    outBytes += (await stat(out)).size
  }

  const largest = (await stat(`${outBase}-${widths.at(-1)}.webp`)).size
  return { key: `images/${relPosix}`, width, height, widths, inBytes: (await stat(file)).size, outBytes, largest }
}

const files = (await walk(SRC_DIR)).sort()
const results = []
// Small concurrency pool – sharp is already multi-threaded internally.
const queue = [...files]
await Promise.all(Array.from({ length: 4 }, async () => {
  while (queue.length) results.push(await processFile(queue.shift()))
}))
results.sort((a, b) => a.key.localeCompare(b.key, 'en', { numeric: true }))

const manifest = Object.fromEntries(results.map((r) => [r.key, { w: r.width, h: r.height, widths: r.widths }]))
await writeFile(
  MANIFEST,
  `// AUTO-GENERATED by scripts/optimize-images.mjs – do not edit by hand.\n` +
  `// Intrinsic size (after EXIF rotation) and generated WebP widths per original image.\n\n` +
  `export interface ImageManifestEntry {\n  w: number\n  h: number\n  widths: number[]\n}\n\n` +
  `export const IMAGE_MANIFEST: Record<string, ImageManifestEntry> = ${JSON.stringify(manifest, null, 2)}\n`,
)

const totalIn = results.reduce((s, r) => s + r.inBytes, 0)
const totalLargest = results.reduce((s, r) => s + r.largest, 0)
const totalOut = results.reduce((s, r) => s + r.outBytes, 0)
console.log(`Optimised ${results.length} images`)
console.log(`  originals:                 ${mb(totalIn)}`)
console.log(`  largest WebP per image:    ${mb(totalLargest)}  (-${(100 - (totalLargest / totalIn) * 100).toFixed(1)}%)`)
console.log(`  all WebP variants on disk: ${mb(totalOut)}`)
if (process.argv.includes('--verbose')) {
  for (const r of results) console.log(`  ${r.key.padEnd(48)} ${kb(r.inBytes).padStart(8)} -> ${kb(r.largest).padStart(7)}  [${r.widths.join(', ')}]`)
}
